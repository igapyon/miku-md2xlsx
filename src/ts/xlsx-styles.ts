import type { CellStyleRole } from "./types.ts";

export function styleIndex(role: CellStyleRole | undefined): number {
  switch (role) {
    case "title":
      return 1;
    case "heading":
      return 2;
    case "tableHeader":
      return 3;
    case "code":
      return 4;
    case "separator":
      return 5;
    case "tableCell":
      return 6;
    default:
      return 0;
  }
}

